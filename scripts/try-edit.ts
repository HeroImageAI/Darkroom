import { chromium } from '@playwright/test';
const items = await (await fetch('http://127.0.0.1:5178/api/items?limit=5')).json();
const it = items.items.find((i: any) => i.kind === 'image' && i.mode === 'generate');
const browser = await chromium.launch({ channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on('pageerror', (e) => console.log('pageerror:', e.message));
await page.goto('http://127.0.0.1:5173/#/edit/' + it.id);
await page.getByRole('button', { name: 'Inpaint' }).click();
await page.waitForTimeout(1500);
const img = page.getByAltText('Picture being edited');
const b = (await img.boundingBox())!;
await page.keyboard.press('b');
await page.mouse.move(b.x + b.width * 0.35, b.y + b.height * 0.45);
await page.mouse.down();
for (let i = 0; i <= 20; i++) await page.mouse.move(b.x + b.width * (0.35 + i * 0.015), b.y + b.height * (0.45 + Math.sin(i / 3) * 0.05));
await page.mouse.up();
await page.getByLabel('What should fill the masked area?').fill('a small glass bottle with a rolled paper message inside');
await page.screenshot({ path: 'proof/B1-edit-mask.png' });
await page.getByRole('button', { name: /Fill masked area/ }).click();
await page.waitForURL((u) => !u.hash.includes(it.id), { timeout: 180000 });
await page.waitForTimeout(2500);
await page.getByRole('button', { name: 'Compare' }).click();
await page.waitForTimeout(800);
await page.screenshot({ path: 'proof/B2-edit-compare.png' });
console.log('new', page.url());
await browser.close();
