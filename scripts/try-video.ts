import { chromium, expect } from '@playwright/test';
const items = await (await fetch('http://127.0.0.1:5178/api/items?limit=20')).json();
const it = items.items.find((i: any) => i.kind === 'image' && i.mode === 'generate' && i.width > i.height);
const browser = await chromium.launch({ channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on('pageerror', (e) => console.log('pageerror:', e.message));
await page.goto('http://127.0.0.1:5173/#/video?start=' + it.id);
await expect(page.getByAltText('Start frame')).toBeVisible({ timeout: 30000 });
await page.getByLabel('Motion prompt').fill('The watch hands sweep forward and the warm light slowly fades to dusk.');
await page.getByRole('button', { name: 'Slow push-in' }).click();
await page.getByRole('button', { name: /Wan 2.2/ }).click();
await page.getByRole('button', { name: '3 s' }).click();
await page.getByRole('button', { name: /Draft/ }).click();
await page.getByLabel('Notify when done').uncheck();
await page.screenshot({ path: 'proof/C1-video-setup.png' });
await page.getByRole('button', { name: /^Animate/ }).click();
await page.waitForTimeout(20000);
await page.screenshot({ path: 'proof/C2-video-running.png' });
await page.reload();
await page.waitForTimeout(3000);
await page.screenshot({ path: 'proof/C3-video-after-reload.png' });
await expect(page.getByTestId('take').first()).toHaveAttribute('data-status', 'done', { timeout: 600000 });
await page.waitForTimeout(3000);
await page.screenshot({ path: 'proof/C4-video-done.png' });
await page.getByRole('button', { name: /Smooth 2/ }).click();
await page.waitForTimeout(1500);
await page.getByRole('button', { name: /Extend \+5/ }).click();
await page.waitForTimeout(4000);
await page.screenshot({ path: 'proof/C5-video-smooth-extend-queued.png' });
console.log('queued smooth + extend');
await browser.close();
