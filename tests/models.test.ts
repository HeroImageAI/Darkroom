import fs from 'node:fs';
import { describe, expect, it } from 'vitest';
import { complete, fitGraph, modelsDirFromYaml, type ModelEntry } from '../src/server/models';

const list: ModelEntry[] = [
  { file: 'flux-2-klein-9b-fp8.safetensors', folder: 'diffusion_models', gb: 9.43, group: 'klein', also: ['flux-2-klein-9b-fp8mixed.safetensors'] },
  { file: 'Flux2-Klein-Image-RestoreV1.safetensors', folder: 'loras', gb: 0.25, group: 'klein', optional: true },
];
const graph = () => ({
  '1': { class_type: 'UNETLoader', inputs: { unet_name: 'flux-2-klein-9b-fp8mixed.safetensors' } },
  '6': { class_type: 'LoraLoaderModelOnly', inputs: { model: ['1', 0], lora_name: 'Flux2-Klein-Image-RestoreV1.safetensors', strength_model: 1 } },
  '9': { class_type: 'KSampler', inputs: { model: ['6', 0], seed: 1 } },
});

describe('models: fit a graph to the models this PC has (DECISIONS 138)', () => {
  it('keeps a graph whose models are all there', () => {
    const g = graph();
    expect(fitGraph(g, list, () => true)).toEqual([]);
    expect(g).toEqual(graph());
  });

  it("swaps in another name of the same model (Black Forest Labs' Klein file for ComfyUI's repack)", () => {
    const g = graph();
    fitGraph(g, list, (_f, n) => n !== 'flux-2-klein-9b-fp8mixed.safetensors');
    expect(g['1'].inputs.unet_name).toBe('flux-2-klein-9b-fp8.safetensors');
  });

  it('leaves out a missing optional LoRA and wires its consumers to the model before it', () => {
    const g = graph() as Record<string, { class_type: string; inputs: Record<string, unknown> }>;
    const left = fitGraph(g, list, (_f, n) => n !== 'Flux2-Klein-Image-RestoreV1.safetensors');
    expect(left).toEqual(['Flux2-Klein-Image-RestoreV1.safetensors']);
    expect(g['6']).toBeUndefined();
    expect(g['9'].inputs.model).toEqual(['1', 0]);
  });

  it('leaves a missing required model alone (ComfyUI then says which file is missing)', () => {
    const g = graph();
    fitGraph(g, list, () => false);
    expect(g['1'].inputs.unet_name).toBe('flux-2-klein-9b-fp8mixed.safetensors');
  });

  it('does not count an error page saved under a model name as the model', () => {
    expect(complete({ gb: 9.43 }, 145)).toBe(false);
    expect(complete({ gb: 9.43 }, 9_433_065_776)).toBe(true);
    expect(complete({ gb: 0.01 }, 3_843_690)).toBe(true);
    expect(complete({ gb: null }, 5_000_000)).toBe(true);
  });

  it("reads ComfyUI's models folder from Comfy Desktop's paths file", () => {
    const yaml = "# Generated by Comfy Desktop\n\ncomfy.desktop_0:\n  base_path: 'D:\\Comfy\\models'\n  is_default: true\n  'loras': 'loras/'\n";
    expect(modelsDirFromYaml(yaml)).toMatch(/Comfy[\\/]models$/);
  });

  it('lists every model with a folder, a size and a source (or a reason there is none)', () => {
    const j = JSON.parse(fs.readFileSync('scripts/models.json', 'utf8')) as { groups: Record<string, string>; models: ModelEntry[] };
    for (const m of j.models) {
      expect(m.folder, m.file).toBeTruthy();
      expect(j.groups[m.group], m.file).toBeTruthy();
      expect((m.repo && m.path) || m.source, m.file).toBeTruthy();
    }
    // only optional models may lack a download
    expect(j.models.filter((m) => !m.repo && !m.optional).map((m) => m.file)).toEqual([]);
  });
});
